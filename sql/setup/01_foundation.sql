-- Run once when setting up a new environment.
-- Existing objects are retained by IF NOT EXISTS.
-- Execute statements in order using an administrator account.

USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS OLIST_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS OLIST;

CREATE SCHEMA IF NOT EXISTS OLIST.RAW;
CREATE SCHEMA IF NOT EXISTS OLIST.STAGING;
CREATE SCHEMA IF NOT EXISTS OLIST.CORE;
CREATE SCHEMA IF NOT EXISTS OLIST.MARTS;

CREATE FILE FORMAT IF NOT EXISTS OLIST.RAW.OLIST_CSV_FORMAT
    TYPE = CSV
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE
    ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;

CREATE STAGE IF NOT EXISTS OLIST.RAW.OLIST_STAGE
    FILE_FORMAT = OLIST.RAW.OLIST_CSV_FORMAT;

USE WAREHOUSE OLIST_WH;
USE DATABASE OLIST;
USE SCHEMA RAW;
